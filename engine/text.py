GLYPHS = {k: np.array([[c == '#' for c in row] for row in v.split('|')]) for k, v in _G.items()}


def text_width(s, spacing=1):
    return max(0, len(s) * (5 + spacing) - spacing)


def text(img, s, x, y, color='dust9', spacing=1, align='left', shadow=None):
    """Draw uppercase text; (x,y) = top-left (or top-center if align='center')."""
    s = s.upper()
    if align == 'center':
        x = x - text_width(s, spacing) // 2
    elif align == 'right':
        x = x - text_width(s, spacing)
    col = P.C(color)
    h, w = img.shape[:2]
    for i, ch in enumerate(s):
        g = GLYPHS.get(ch, GLYPHS['?'])
        gx = x + i * (5 + spacing)
        for dy, dx in zip(*np.nonzero(g)):
            for (ox, oy, c) in ([(1, 1, P.C(shadow))] if shadow else []) + [(0, 0, col)]:
                px, py = gx + dx + ox, y + dy + oy
                if 0 <= px < w and 0 <= py < h:
                    img[py, px, :3] = c
                    if img.shape[-1] == 4:
                        img[py, px, 3] = 255
    return img
